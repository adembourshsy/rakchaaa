export function getCarsByDifficulty(
  difficulty: 'beginner' | 'intermediate' | 'expert',
  count: number,
  customPool?: CarData[]
): CarData[] {
  const source = customPool && customPool.length > 0 ? customPool : CAR_DATABASE;
  const filtered = source.filter(c => c.difficulty === difficulty);
  const pool = filtered.length >= count ? filtered : source;
  
  // Shuffle pool
  const shuffled = [...pool].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
}
